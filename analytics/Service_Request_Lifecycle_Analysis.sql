

SELECT
    SERVICE_TYPE,
    SERVICE_STATUS,

    COUNT(DISTINCT SERVICE_REQUEST_ID) AS TOTAL_SERVICE_REQUESTS,

    COUNT(
        CASE
            WHEN CASE_RESOLVED_FLAG = TRUE THEN SERVICE_REQUEST_ID
        END
    ) AS RESOLVED_REQUESTS,

    ROUND(
        AVG(TOTAL_LIFECYCLE_HOURS),
        2
    ) AS AVG_TOTAL_LIFECYCLE_HOURS

FROM MARTS.MART_SERVICE_REQUEST_LIFECYCLE

GROUP BY
    SERVICE_TYPE,
    SERVICE_STATUS

ORDER BY
    TOTAL_SERVICE_REQUESTS DESC;
