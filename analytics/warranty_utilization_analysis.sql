/*
Business Question:
How are warranty entitlements being used across mail-in and onsite repair options?

Purpose:
This query measures warranty utilization, active warranty service usage,
expired warranty contacts, and conversion from support contact to service request.
*/

SELECT
    WARRANTY_TYPE,
    ENTITLEMENT_LEVEL,
    WARRANTY_STATUS,
    REPAIR_COVERAGE_TYPE,

    SUM(TOTAL_ASSETS) AS TOTAL_ASSETS,
    SUM(TOTAL_CUSTOMERS) AS TOTAL_CUSTOMERS,
    SUM(TOTAL_SUPPORT_CONTACTS) AS TOTAL_SUPPORT_CONTACTS,
    SUM(TOTAL_SERVICE_REQUESTS) AS TOTAL_SERVICE_REQUESTS,

    SUM(MAIL_IN_SERVICE_REQUESTS) AS MAIL_IN_SERVICE_REQUESTS,
    SUM(ONSITE_SERVICE_REQUESTS) AS ONSITE_SERVICE_REQUESTS,
    SUM(ACTIVE_WARRANTY_SERVICE_REQUESTS) AS ACTIVE_WARRANTY_SERVICE_REQUESTS,
    SUM(EXPIRED_WARRANTY_CONTACTS) AS EXPIRED_WARRANTY_CONTACTS,

    ROUND(
        SUM(TOTAL_SERVICE_REQUESTS) * 100.0
        / NULLIF(SUM(TOTAL_SUPPORT_CONTACTS), 0),
        2
    ) AS WARRANTY_SERVICE_CONVERSION_RATE

FROM MARTS.MART_WARRANTY_UTILIZATION

GROUP BY
    WARRANTY_TYPE,
    ENTITLEMENT_LEVEL,
    WARRANTY_STATUS,
    REPAIR_COVERAGE_TYPE

ORDER BY
    TOTAL_SERVICE_REQUESTS DESC;
`
