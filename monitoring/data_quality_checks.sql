/*
Purpose:
This script creates a centralized data quality results view for the warranty
service request and repair lifecycle analytics platform.

Business Value:
The checks validate completeness, uniqueness, relationship integrity, and
operational readiness before the data is used for lifecycle analytics.
*/

USE DATABASE WARRANTY_SERVICE_ANALYTICS_DB;
USE SCHEMA MONITORING;

CREATE OR REPLACE VIEW DATA_QUALITY_RESULTS AS

SELECT
    'CUSTOMERS_ROW_COUNT_CHECK' AS TEST_NAME,
    'STG_CUSTOMERS' AS TABLE_NAME,
    CASE
        WHEN COUNT(*) > 0 THEN 'PASS'
        ELSE 'FAIL'
    END AS STATUS,
    COUNT(*) AS METRIC_VALUE,
    CURRENT_TIMESTAMP AS TEST_EXECUTED_AT
FROM STAGING.STG_CUSTOMERS

UNION ALL

SELECT
    'CUSTOMERS_PRIMARY_KEY_NULL_CHECK' AS TEST_NAME,
    'STG_CUSTOMERS' AS TABLE_NAME,
    CASE
        WHEN COUNT(*) = 0 THEN 'PASS'
        ELSE 'FAIL'
    END AS STATUS,
    COUNT(*) AS METRIC_VALUE,
    CURRENT_TIMESTAMP AS TEST_EXECUTED_AT
FROM STAGING.STG_CUSTOMERS
WHERE CUSTOMER_ID IS NULL

UNION ALL

SELECT
    'CUSTOMERS_DUPLICATE_CHECK' AS TEST_NAME,
    'STG_CUSTOMERS' AS TABLE_NAME,
    CASE
        WHEN COUNT(*) = 0 THEN 'PASS'
        ELSE 'FAIL'
    END AS STATUS,
    COUNT(*) AS METRIC_VALUE,
    CURRENT_TIMESTAMP AS TEST_EXECUTED_AT
FROM (
    SELECT
        CUSTOMER_ID
    FROM STAGING.STG_CUSTOMERS
    GROUP BY CUSTOMER_ID
    HAVING COUNT(*) > 1
)

UNION ALL

SELECT
    'PRODUCT_ASSETS_ROW_COUNT_CHECK' AS TEST_NAME,
    'STG_PRODUCT_ASSETS' AS TABLE_NAME,
    CASE
        WHEN COUNT(*) > 0 THEN 'PASS'
        ELSE 'FAIL'
    END AS STATUS,
    COUNT(*) AS METRIC_VALUE,
    CURRENT_TIMESTAMP AS TEST_EXECUTED_AT
FROM STAGING.STG_PRODUCT_ASSETS

UNION ALL

SELECT
    'PRODUCT_ASSETS_CUSTOMER_RELATIONSHIP_CHECK' AS TEST_NAME,
    'STG_PRODUCT_ASSETS' AS TABLE_NAME,
    CASE
        WHEN COUNT(*) = 0 THEN 'PASS'
        ELSE 'FAIL'
    END AS STATUS,
    COUNT(*) AS METRIC_VALUE,
    CURRENT_TIMESTAMP AS TEST_EXECUTED_AT
FROM STAGING.STG_PRODUCT_ASSETS p
LEFT JOIN STAGING.STG_CUSTOMERS c
    ON p.CUSTOMER_ID = c.CUSTOMER_ID
WHERE c.CUSTOMER_ID IS NULL

UNION ALL

SELECT
    'CUSTOMER_CONTACTS_ROW_COUNT_CHECK' AS TEST_NAME,
    'STG_CUSTOMER_CONTACTS' AS TABLE_NAME,
    CASE
        WHEN COUNT(*) > 0 THEN 'PASS'
        ELSE 'FAIL'
    END AS STATUS,
    COUNT(*) AS METRIC_VALUE,
    CURRENT_TIMESTAMP AS TEST_EXECUTED_AT
FROM STAGING.STG_CUSTOMER_CONTACTS

UNION ALL

SELECT
    'CUSTOMER_CONTACTS_VALID_CHANNEL_CHECK' AS TEST_NAME,
    'STG_CUSTOMER_CONTACTS' AS TABLE_NAME,
    CASE
        WHEN COUNT(*) = 0 THEN 'PASS'
        ELSE 'FAIL'
    END AS STATUS,
    COUNT(*) AS METRIC_VALUE,
    CURRENT_TIMESTAMP AS TEST_EXECUTED_AT
FROM STAGING.STG_CUSTOMER_CONTACTS
WHERE CONTACT_CHANNEL NOT IN (
    'VOICE',
    'CHAT',
    'SOCIAL_FACEBOOK',
    'SOCIAL_OTHER'
)

UNION ALL

SELECT
    'SERVICE_REQUESTS_ROW_COUNT_CHECK' AS TEST_NAME,
    'STG_SERVICE_REQUESTS' AS TABLE_NAME,
    CASE
        WHEN COUNT(*) > 0 THEN 'PASS'
        ELSE 'FAIL'
    END AS STATUS,
    COUNT(*) AS METRIC_VALUE,
    CURRENT_TIMESTAMP AS TEST_EXECUTED_AT
FROM STAGING.STG_SERVICE_REQUESTS

UNION ALL

SELECT
    'SERVICE_REQUEST_CONTACT_RELATIONSHIP_CHECK' AS TEST_NAME,
    'STG_SERVICE_REQUESTS' AS TABLE_NAME,
    CASE
        WHEN COUNT(*) = 0 THEN 'PASS'
        ELSE 'FAIL'
    END AS STATUS,
    COUNT(*) AS METRIC_VALUE,
    CURRENT_TIMESTAMP AS TEST_EXECUTED_AT
FROM STAGING.STG_SERVICE_REQUESTS s
LEFT JOIN STAGING.STG_CUSTOMER_CONTACTS c
    ON s.CONTACT_ID = c.CONTACT_ID
WHERE c.CONTACT_ID IS NULL

UNION ALL

SELECT
    'WARRANTY_ENTITLEMENTS_ROW_COUNT_CHECK' AS TEST_NAME,
    'STG_WARRANTY_ENTITLEMENTS' AS TABLE_NAME,
    CASE
        WHEN COUNT(*) > 0 THEN 'PASS'
        ELSE 'FAIL'
    END AS STATUS,
    COUNT(*) AS METRIC_VALUE,
    CURRENT_TIMESTAMP AS TEST_EXECUTED_AT
FROM STAGING.STG_WARRANTY_ENTITLEMENTS

UNION ALL

SELECT
    'WARRANTY_DATE_VALIDITY_CHECK' AS TEST_NAME,
    'STG_WARRANTY_ENTITLEMENTS' AS TABLE_NAME,
    CASE
        WHEN COUNT(*) = 0 THEN 'PASS'
        ELSE 'FAIL'
    END AS STATUS,
    COUNT(*) AS METRIC_VALUE,
    CURRENT_TIMESTAMP AS TEST_EXECUTED_AT
FROM STAGING.STG_WARRANTY_ENTITLEMENTS
WHERE WARRANTY_END_DATE < WARRANTY_START_DATE

UNION ALL

SELECT
    'REPAIR_EVENTS_ROW_COUNT_CHECK' AS TEST_NAME,
    'STG_REPAIR_EVENTS' AS TABLE_NAME,
    CASE
        WHEN COUNT(*) > 0 THEN 'PASS'
        ELSE 'FAIL'
    END AS STATUS,
    COUNT(*) AS METRIC_VALUE,
    CURRENT_TIMESTAMP AS TEST_EXECUTED_AT
FROM STAGING.STG_REPAIR_EVENTS

UNION ALL

SELECT
    'REPAIR_SERVICE_REQUEST_RELATIONSHIP_CHECK' AS TEST_NAME,
    'STG_REPAIR_EVENTS' AS TABLE_NAME,
    CASE
        WHEN COUNT(*) = 0 THEN 'PASS'
        ELSE 'FAIL'
    END AS STATUS,
    COUNT(*) AS METRIC_VALUE,
    CURRENT_TIMESTAMP AS TEST_EXECUTED_AT
FROM STAGING.STG_REPAIR_EVENTS r
LEFT JOIN STAGING.STG_SERVICE_REQUESTS s
    ON r.SERVICE_REQUEST_ID = s.SERVICE_REQUEST_ID
WHERE s.SERVICE_REQUEST_ID IS NULL

UNION ALL

SELECT
    'CASE_CLOSURES_ROW_COUNT_CHECK' AS TEST_NAME,
    'STG_CASE_CLOSURES' AS TABLE_NAME,
    CASE
        WHEN COUNT(*) > 0 THEN 'PASS'
        ELSE 'FAIL'
    END AS STATUS,
    COUNT(*) AS METRIC_VALUE,
    CURRENT_TIMESTAMP AS TEST_EXECUTED_AT
FROM STAGING.STG_CASE_CLOSURES

UNION ALL

SELECT
    'CASE_CLOSURE_SERVICE_REQUEST_RELATIONSHIP_CHECK' AS TEST_NAME,
    'STG_CASE_CLOSURES' AS TABLE_NAME,
    CASE
        WHEN COUNT(*) = 0 THEN 'PASS'
        ELSE 'FAIL'
    END AS STATUS,
    COUNT(*) AS METRIC_VALUE,
    CURRENT_TIMESTAMP AS TEST_EXECUTED_AT
FROM STAGING.STG_CASE_CLOSURES cc
LEFT JOIN STAGING.STG_SERVICE_REQUESTS s
    ON cc.SERVICE_REQUEST_ID = s.SERVICE_REQUEST_ID
WHERE s.SERVICE_REQUEST_ID IS NULL;
