/*
Purpose:
This script creates an incremental load audit table used to track source-level
loads, last successful ingestion timestamps, batch status, and record counts.

Business Value:
This supports incremental processing by helping the platform identify what data
has already been loaded and what new records should be processed in future runs.
*/

USE DATABASE WARRANTY_SERVICE_ANALYTICS_DB;
USE SCHEMA MONITORING;

CREATE OR REPLACE TABLE INCREMENTAL_LOAD_AUDIT (
    AUDIT_ID STRING,
    SOURCE_TABLE_NAME STRING,
    SOURCE_FILE_NAME STRING,
    BATCH_ID STRING,
    LAST_SUCCESSFUL_LOAD_TIMESTAMP TIMESTAMP_NTZ,
    RECORDS_PROCESSED NUMBER,
    LOAD_STATUS STRING,
    LOAD_STARTED_AT TIMESTAMP_NTZ,
    LOAD_COMPLETED_AT TIMESTAMP_NTZ,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO INCREMENTAL_LOAD_AUDIT (
    AUDIT_ID,
    SOURCE_TABLE_NAME,
    SOURCE_FILE_NAME,
    BATCH_ID,
    LAST_SUCCESSFUL_LOAD_TIMESTAMP,
    RECORDS_PROCESSED,
    LOAD_STATUS,
    LOAD_STARTED_AT,
    LOAD_COMPLETED_AT
)

SELECT
    'AUD_CUSTOMERS_001' AS AUDIT_ID,
    'CUSTOMERS_RAW' AS SOURCE_TABLE_NAME,
    'customers.json' AS SOURCE_FILE_NAME,
    'BATCH_001' AS BATCH_ID,
    MAX(INGESTED_AT) AS LAST_SUCCESSFUL_LOAD_TIMESTAMP,
    COUNT(*) AS RECORDS_PROCESSED,
    'SUCCESS' AS LOAD_STATUS,
    MIN(INGESTED_AT) AS LOAD_STARTED_AT,
    MAX(INGESTED_AT) AS LOAD_COMPLETED_AT
FROM RAW.CUSTOMERS_RAW

