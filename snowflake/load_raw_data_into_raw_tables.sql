TRUNCATE TABLE CUSTOMERS_RAW;
TRUNCATE TABLE PRODUCT_ASSETS_RAW;
TRUNCATE TABLE CUSTOMER_CONTACTS_RAW;
TRUNCATE TABLE WARRANTY_ENTITLEMENTS_RAW;
TRUNCATE TABLE SERVICE_REQUESTS_RAW;
TRUNCATE TABLE REPAIR_EVENTS_RAW;
TRUNCATE TABLE CASE_CLOSURES_RAW;

INSERT INTO CUSTOMERS_RAW (
    RAW_RECORD,
    SOURCE_FILE_NAME
)
SELECT
    $1 AS RAW_RECORD,
    METADATA$FILENAME AS SOURCE_FILE_NAME
FROM @RAW_JSON_STAGE/customers.json
(
    FILE_FORMAT => JSON_FILE_FORMAT
