CREATE OR REPLACE VIEW STAGING.STG_WARRANTY_ENTITLEMENTS AS

SELECT
    RAW_RECORD:warranty_id::STRING AS WARRANTY_ID,
    RAW_RECORD:asset_id::STRING AS ASSET_ID,
    RAW_RECORD:customer_id::STRING AS CUSTOMER_ID,
    RAW_RECORD:warranty_type::STRING AS WARRANTY_TYPE,
    RAW_RECORD:entitlement_level::STRING AS ENTITLEMENT_LEVEL,
    TO_DATE(RAW_RECORD:warranty_start_date::STRING) AS WARRANTY_START_DATE,
    TO_DATE(RAW_RECORD:warranty_end_date::STRING) AS WARRANTY_END_DATE,
    RAW_RECORD:warranty_status::STRING AS WARRANTY_STATUS,
    RAW_RECORD:repair_coverage_type::STRING AS REPAIR_COVERAGE_TYPE,
    RAW_RECORD:onsite_eligible_flag::BOOLEAN AS ONSITE_ELIGIBLE_FLAG,
    RAW_RECORD:mailin_eligible_flag::BOOLEAN AS MAILIN_ELIGIBLE_FLAG,
    TO_TIMESTAMP_NTZ(RAW_RECORD:created_at::STRING) AS CREATED_AT,
    SOURCE_FILE_NAME,
    INGESTED_AT
FROM RAW.WARRANTY_ENTITLEMENTS_RAW;



