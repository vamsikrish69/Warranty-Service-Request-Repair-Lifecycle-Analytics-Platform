CREATE OR REPLACE VIEW STAGING.STG_CASE_CLOSURES AS

SELECT
    RAW_RECORD:closure_id::STRING AS CLOSURE_ID,
    RAW_RECORD:service_request_id::STRING AS SERVICE_REQUEST_ID,
    TO_TIMESTAMP_NTZ(RAW_RECORD:case_closed_at::STRING) AS CASE_CLOSED_AT,
    RAW_RECORD:closure_reason::STRING AS CLOSURE_REASON,
    RAW_RECORD:resolution_status::STRING AS RESOLUTION_STATUS,
    RAW_RECORD:customer_satisfaction_score::NUMBER AS CUSTOMER_SATISFACTION_SCORE,
    RAW_RECORD:reopen_flag::BOOLEAN AS REOPEN_FLAG,
    TO_TIMESTAMP_NTZ(RAW_RECORD:updated_at::STRING) AS UPDATED_AT,
    SOURCE_FILE_NAME,
    INGESTED_AT
FROM RAW.CASE_CLOSURES_RAW;
