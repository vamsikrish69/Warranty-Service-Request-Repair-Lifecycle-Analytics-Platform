CREATE OR REPLACE VIEW STAGING.STG_SERVICE_REQUESTS AS

SELECT
    RAW_RECORD:service_request_id::STRING AS SERVICE_REQUEST_ID,
    RAW_RECORD:contact_id::STRING AS CONTACT_ID,
    RAW_RECORD:customer_id::STRING AS CUSTOMER_ID,
    RAW_RECORD:asset_id::STRING AS ASSET_ID,
    RAW_RECORD:warranty_id::STRING AS WARRANTY_ID,
    TO_TIMESTAMP_NTZ(RAW_RECORD:service_created_at::STRING) AS SERVICE_CREATED_AT,
    RAW_RECORD:service_type::STRING AS SERVICE_TYPE,
    RAW_RECORD:service_status::STRING AS SERVICE_STATUS,
    RAW_RECORD:priority::STRING AS PRIORITY,
    RAW_RECORD:sla_target_hours::NUMBER AS SLA_TARGET_HOURS,
    RAW_RECORD:escalation_flag::BOOLEAN AS ESCALATION_FLAG,
    RAW_RECORD:repeat_request_flag::BOOLEAN AS REPEAT_REQUEST_FLAG,
    RAW_RECORD:created_by_channel::STRING AS CREATED_BY_CHANNEL,
    RAW_RECORD:region::STRING AS REGION,
    RAW_RECORD:country::STRING AS COUNTRY,
    TO_TIMESTAMP_NTZ(RAW_RECORD:updated_at::STRING) AS UPDATED_AT,
    SOURCE_FILE_NAME,
    INGESTED_AT
FROM RAW.SERVICE_REQUESTS_RAW;
``
