CREATE OR REPLACE VIEW STAGING.STG_PRODUCT_ASSETS AS

SELECT
    RAW_RECORD:asset_id::STRING AS ASSET_ID,
    RAW_RECORD:customer_id::STRING AS CUSTOMER_ID,
    RAW_RECORD:service_tag::STRING AS SERVICE_TAG,
    RAW_RECORD:product_line::STRING AS PRODUCT_LINE,
    RAW_RECORD:product_model::STRING AS PRODUCT_MODEL,
    TO_DATE(RAW_RECORD:purchase_date::STRING) AS PURCHASE_DATE,
    TO_DATE(RAW_RECORD:ship_date::STRING) AS SHIP_DATE,
    RAW_RECORD:region::STRING AS REGION,
    RAW_RECORD:country::STRING AS COUNTRY,
    SOURCE_FILE_NAME,
    INGESTED_AT
FROM RAW.PRODUCT_ASSETS_RAW;



