CREATE OR REPLACE VIEW STAGING.STG_REPAIR_EVENTS AS

SELECT
    RAW_RECORD:repair_event_id::STRING AS REPAIR_EVENT_ID,
    RAW_RECORD:service_request_id::STRING AS SERVICE_REQUEST_ID,
    RAW_RECORD:repair_type::STRING AS REPAIR_TYPE,
    RAW_RECORD:repair_center_id::STRING AS REPAIR_CENTER_ID,
    RAW_RECORD:technician_id::STRING AS TECHNICIAN_ID,
    TO_TIMESTAMP_NTZ(RAW_RECORD:repair_created_at::STRING) AS REPAIR_CREATED_AT,
    TO_TIMESTAMP_NTZ(RAW_RECORD:repair_started_at::STRING) AS REPAIR_STARTED_AT,
    TO_TIMESTAMP_NTZ(RAW_RECORD:repair_completed_at::STRING) AS REPAIR_COMPLETED_AT,
    RAW_RECORD:parts_required_flag::BOOLEAN AS PARTS_REQUIRED_FLAG,
    RAW_RECORD:part_delay_flag::BOOLEAN AS PART_DELAY_FLAG,
    RAW_RECORD:repair_status::STRING AS REPAIR_STATUS,
    RAW_RECORD:repair_outcome::STRING AS REPAIR_OUTCOME,
    TO_TIMESTAMP_NTZ(RAW_RECORD:updated_at::STRING) AS UPDATED_AT,
    SOURCE_FILE_NAME,
    INGESTED_AT
FROM RAW.REPAIR_EVENTS_RAW;



