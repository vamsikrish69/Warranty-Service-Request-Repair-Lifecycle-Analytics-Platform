CREATE OR REPLACE VIEW STAGING.STG_CUSTOMERS AS

SELECT
    RAW_RECORD:customer_id::STRING AS CUSTOMER_ID,
    RAW_RECORD:customer_name::STRING AS CUSTOMER_NAME,
    RAW_RECORD:customer_type::STRING AS CUSTOMER_TYPE,
    RAW_RECORD:email::STRING AS EMAIL,
    RAW_RECORD:phone::STRING AS PHONE,
    RAW_RECORD:region::STRING AS REGION,
    RAW_RECORD:country::STRING AS COUNTRY,
    RAW_RECORD:city::STRING AS CITY,
    TO_TIMESTAMP_NTZ(RAW_RECORD:created_at::STRING) AS CREATED_AT,
    SOURCE_FILE_NAME,
    INGESTED_AT
FROM RAW.CUSTOMERS_RAW;



