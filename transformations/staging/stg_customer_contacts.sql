CREATE OR REPLACE VIEW STAGING.STG_CUSTOMER_CONTACTS AS

SELECT
    RAW_RECORD:contact_id::STRING AS CONTACT_ID,
    RAW_RECORD:customer_id::STRING AS CUSTOMER_ID,
    RAW_RECORD:asset_id::STRING AS ASSET_ID,
    RAW_RECORD:contact_channel::STRING AS CONTACT_CHANNEL,
    TO_TIMESTAMP_NTZ(RAW_RECORD:contact_timestamp::STRING) AS CONTACT_TIMESTAMP,
    RAW_RECORD:issue_category::STRING AS ISSUE_CATEGORY,
    RAW_RECORD:issue_description::STRING AS ISSUE_DESCRIPTION,
    RAW_RECORD:agent_id::STRING AS AGENT_ID,
    RAW_RECORD:region::STRING AS REGION,
    RAW_RECORD:country::STRING AS COUNTRY,
    RAW_RECORD:troubleshooting_attempted_flag::BOOLEAN AS TROUBLESHOOTING_ATTEMPTED_FLAG,
    RAW_RECORD:resolved_during_contact_flag::BOOLEAN AS RESOLVED_DURING_CONTACT_FLAG,
    RAW_RECORD:followup_required_flag::BOOLEAN AS FOLLOWUP_REQUIRED_FLAG,
    RAW_RECORD:service_required_flag::BOOLEAN AS SERVICE_REQUIRED_FLAG,
    RAW_RECORD:source_system::STRING AS SOURCE_SYSTEM,
    TO_TIMESTAMP_NTZ(RAW_RECORD:updated_at::STRING) AS UPDATED_AT,
    SOURCE_FILE_NAME,
    INGESTED_AT
FROM RAW.CUSTOMER_CONTACTS_RAW;





