create or replace view WARRANTY_SERVICE_ANALYTICS_DB.INTERMEDIATE.INT_WARRANTY_VALIDATION(
	CONTACT_ID,
	CUSTOMER_ID,
	ASSET_ID,
	CONTACT_CHANNEL,
	CONTACT_TIMESTAMP,
	ISSUE_CATEGORY,
	ISSUE_DESCRIPTION,
	REGION,
	COUNTRY,
	TROUBLESHOOTING_ATTEMPTED_FLAG,
	RESOLVED_DURING_CONTACT_FLAG,
	FOLLOWUP_REQUIRED_FLAG,
	SERVICE_REQUIRED_FLAG,
	SERVICE_REQUEST_ID,
	SERVICE_CREATED_AT,
	SERVICE_TYPE,
	SERVICE_STATUS,
	PRIORITY,
	SLA_TARGET_HOURS,
	ESCALATION_FLAG,
	REPEAT_REQUEST_FLAG,
	CREATED_BY_CHANNEL,
	CONTACT_TO_SERVICE_HOURS,
	SERVICE_CREATED_FLAG,
	FIRST_CONTACT_RESOLVED_FLAG,
	CONTACT_CONVERTED_TO_SERVICE_FLAG,
	WARRANTY_ID,
	WARRANTY_TYPE,
	ENTITLEMENT_LEVEL,
	WARRANTY_STATUS,
	REPAIR_COVERAGE_TYPE,
	ONSITE_ELIGIBLE_FLAG,
	MAILIN_ELIGIBLE_FLAG,
	WARRANTY_START_DATE,
	WARRANTY_END_DATE,
	WARRANTY_FOUND_FLAG,
	ACTIVE_WARRANTY_FLAG,
	EXPIRED_WARRANTY_FLAG,
	ONSITE_REPAIR_ELIGIBLE_FLAG,
	MAILIN_REPAIR_ELIGIBLE_FLAG
) as

SELECT
    l.*,

    w.WARRANTY_ID,
    w.WARRANTY_TYPE,
    w.ENTITLEMENT_LEVEL,
    w.WARRANTY_STATUS,
    w.REPAIR_COVERAGE_TYPE,
    w.ONSITE_ELIGIBLE_FLAG,
    w.MAILIN_ELIGIBLE_FLAG,
    w.WARRANTY_START_DATE,
    w.WARRANTY_END_DATE,

    CASE
        WHEN w.WARRANTY_ID IS NOT NULL THEN TRUE
        ELSE FALSE
    END AS WARRANTY_FOUND_FLAG,

    CASE
        WHEN w.WARRANTY_STATUS = 'ACTIVE' THEN TRUE
        ELSE FALSE
    END AS ACTIVE_WARRANTY_FLAG,

    CASE
        WHEN w.WARRANTY_STATUS = 'EXPIRED' THEN TRUE
        ELSE FALSE
    END AS EXPIRED_WARRANTY_FLAG,

    CASE
        WHEN w.ONSITE_ELIGIBLE_FLAG = TRUE THEN TRUE
        ELSE FALSE
    END AS ONSITE_REPAIR_ELIGIBLE_FLAG,

    CASE
        WHEN w.MAILIN_ELIGIBLE_FLAG = TRUE THEN TRUE
        ELSE FALSE
    END AS MAILIN_REPAIR_ELIGIBLE_FLAG

FROM INTERMEDIATE.INT_CONTACT_SERVICE_LIFECYCLE l

LEFT JOIN STAGING.STG_WARRANTY_ENTITLEMENTS w
    ON l.ASSET_ID = w.ASSET_ID;
