CREATE OR REPLACE VIEW INTERMEDIATE.INT_WARRANTY_VALIDATION AS

SELECT

    l.*,

    w.WARRANTY_ID,
    w.WARRAN*Y_TYPE,
    w.ENTITLEMENT_LEVEL,
 *  w.WARRANTY_STATUS,
    w.REPAIR_*OVERAGE_TYPE,

    w.ONSITE_ELIGIB*E_FLAG,
*  *w.MAILIN_ELIGIBLE_FLAG

FROM INTER*EDIATE.INT_CONTACT_SERVICE_LIFECYC*E l

LEFT JOIN STAGING.STG_WARRANT*_ENTITLEMENTS w
    ON l.ASSET_ID * w.ASSET_ID;
