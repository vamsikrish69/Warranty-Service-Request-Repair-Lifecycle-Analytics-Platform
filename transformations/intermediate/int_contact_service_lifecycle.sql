create or replace view WARRANTY_SERVICE_ANALYTICS_DB.INTERMEDIATE.INT_CONTACT_SERVICE_LIFECYCLE(
	CONTACT_ID,
	CUSTOMER_ID,
	ASSET_ID,
	CONTACT_CHANNEL,
	CONTACT_TIMESTAMP,
	ISSUE_CATEGORY,
	ISSUE_DESCRIPTION,
	REGION,
	COUNTRY,
	TROUBLESHOOTING_ATTEMPTED_FLAG,
	RESOLVED_DURING_CONTACT_FLAG,
	FOLLOWUP_REQUIRED_FLAG,
	SERVICE_REQUIRED_FLAG,
	SERVICE_REQUEST_ID,
	SERVICE_CREATED_AT,
	SERVICE_TYPE,
	SERVICE_STATUS,
	PRIORITY,
	SLA_TARGET_HOURS,
	ESCALATION_FLAG,
	REPEAT_REQUEST_FLAG,
	CREATED_BY_CHANNEL,
	CONTACT_TO_SERVICE_HOURS,
	SERVICE_CREATED_FLAG,
	FIRST_CONTACT_RESOLVED_FLAG,
	CONTACT_CONVERTED_TO_SERVICE_FLAG
) as

SELECT
    c.CONTACT_ID,
    c.CUSTOMER_ID,
    c.ASSET_ID,

    c.CONTACT_CHANNEL,
    c.CONTACT_TIMESTAMP,

    c.ISSUE_CATEGORY,
    c.ISSUE_DESCRIPTION,

    c.REGION,
    c.COUNTRY,

    c.TROUBLESHOOTING_ATTEMPTED_FLAG,
    c.RESOLVED_DURING_CONTACT_FLAG,
    c.FOLLOWUP_REQUIRED_FLAG,
    c.SERVICE_REQUIRED_FLAG,

    s.SERVICE_REQUEST_ID,
    s.SERVICE_CREATED_AT,
    s.SERVICE_TYPE,
    s.SERVICE_STATUS,
    s.PRIORITY,
    s.SLA_TARGET_HOURS,
    s.ESCALATION_FLAG,
    s.REPEAT_REQUEST_FLAG,
    s.CREATED_BY_CHANNEL,

    DATEDIFF(
        'HOUR',
        c.CONTACT_TIMESTAMP,
        s.SERVICE_CREATED_AT
    ) AS CONTACT_TO_SERVICE_HOURS,

    CASE
        WHEN s.SERVICE_REQUEST_ID IS NOT NULL THEN TRUE
        ELSE FALSE
    END AS SERVICE_CREATED_FLAG,

    CASE
        WHEN c.RESOLVED_DURING_CONTACT_FLAG = TRUE THEN TRUE
        ELSE FALSE
    END AS FIRST_CONTACT_RESOLVED_FLAG,

    CASE
        WHEN c.SERVICE_REQUIRED_FLAG = TRUE
             AND s.SERVICE_REQUEST_ID IS NOT NULL
        THEN TRUE
        ELSE FALSE
    END AS CONTACT_CONVERTED_TO_SERVICE_FLAG

FROM STAGING.STG_CUSTOMER_CONTACTS c

LEFT JOIN STAGING.STG_SERVICE_REQUESTS s
    ON c.CONTACT_ID = s.CONTACT_ID;
