create or replace view WARRANTY_SERVICE_ANALYTICS_DB.INTERMEDIATE.INT_CASE_RESOLUTION(
	CONTACT_ID,
	CUSTOMER_ID,
	ASSET_ID,
	CONTACT_CHANNEL,
	CONTACT_TIMESTAMP,
	ISSUE_CATEGORY,
	ISSUE_DESCRIPTION,
	REGION,
	COUNTRY,
	TROUBLESHOOTING_ATTEMPTED_FLAG,
	RESOLVED_DURING_CONTACT_FLAG,
	FOLLOWUP_REQUIRED_FLAG,
	SERVICE_REQUIRED_FLAG,
	SERVICE_REQUEST_ID,
	SERVICE_CREATED_AT,
	SERVICE_TYPE,
	SERVICE_STATUS,
	PRIORITY,
	SLA_TARGET_HOURS,
	ESCALATION_FLAG,
	REPEAT_REQUEST_FLAG,
	CREATED_BY_CHANNEL,
	CONTACT_TO_SERVICE_HOURS,
	SERVICE_CREATED_FLAG,
	FIRST_CONTACT_RESOLVED_FLAG,
	CONTACT_CONVERTED_TO_SERVICE_FLAG,
	WARRANTY_ID,
	WARRANTY_TYPE,
	ENTITLEMENT_LEVEL,
	WARRANTY_STATUS,
	REPAIR_COVERAGE_TYPE,
	ONSITE_ELIGIBLE_FLAG,
	MAILIN_ELIGIBLE_FLAG,
	WARRANTY_START_DATE,
	WARRANTY_END_DATE,
	WARRANTY_FOUND_FLAG,
	ACTIVE_WARRANTY_FLAG,
	EXPIRED_WARRANTY_FLAG,
	ONSITE_REPAIR_ELIGIBLE_FLAG,
	MAILIN_REPAIR_ELIGIBLE_FLAG,
	REPAIR_EVENT_ID,
	REPAIR_TYPE,
	REPAIR_CENTER_ID,
	TECHNICIAN_ID,
	REPAIR_CREATED_AT,
	REPAIR_STARTED_AT,
	REPAIR_COMPLETED_AT,
	PARTS_REQUIRED_FLAG,
	PART_DELAY_FLAG,
	REPAIR_STATUS,
	REPAIR_OUTCOME,
	REPAIR_WAIT_TIME_HOURS,
	REPAIR_TURNAROUND_HOURS,
	REPAIR_EVENT_CREATED_FLAG,
	REPAIR_COMPLETED_FLAG,
	PART_DELAY_IMPACT_FLAG,
	OPEN_REPAIR_FLAG,
	CLOSURE_ID,
	CASE_CLOSED_AT,
	CLOSURE_REASON,
	RESOLUTION_STATUS,
	CUSTOMER_SATISFACTION_SCORE,
	REOPEN_FLAG,
	TOTAL_LIFECYCLE_HOURS,
	CASE_CLOSED_FLAG,
	CASE_RESOLVED_FLAG,
	CASE_REOPENED_FLAG
) as

SELECT
    r.*,

    c.CLOSURE_ID,
    c.CASE_CLOSED_AT,
    c.CLOSURE_REASON,
    c.RESOLUTION_STATUS,
    c.CUSTOMER_SATISFACTION_SCORE,
    c.REOPEN_FLAG,

    DATEDIFF(
        'HOUR',
        r.CONTACT_TIMESTAMP,
        c.CASE_CLOSED_AT
    ) AS TOTAL_LIFECYCLE_HOURS,

    CASE
        WHEN c.CLOSURE_ID IS NOT NULL THEN TRUE
        ELSE FALSE
    END AS CASE_CLOSED_FLAG,

    CASE
        WHEN c.RESOLUTION_STATUS = 'RESOLVED' THEN TRUE
        ELSE FALSE
    END AS CASE_RESOLVED_FLAG,

    CASE
        WHEN c.REOPEN_FLAG = TRUE THEN TRUE
        ELSE FALSE
    END AS CASE_REOPENED_FLAG

FROM INTERMEDIATE.INT_REPAIR_FULFILLMENT r

LEFT JOIN STAGING.STG_CASE_CLOSURES c
    ON r.SERVICE_REQUEST_ID = c.SERVICE_REQUEST_ID;
