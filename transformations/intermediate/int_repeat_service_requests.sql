create or replace view WARRANTY_SERVICE_ANALYTICS_DB.INTERMEDIATE.INT_REPEAT_SERVICE_REQUESTS(
	CUSTOMER_ID,
	ASSET_ID,
	SERVICE_REQUEST_ID,
	SERVICE_CREATED_AT,
	SERVICE_TYPE,
	SERVICE_STATUS,
	PRIORITY,
	REGION,
	COUNTRY,
	PREVIOUS_SERVICE_REQUEST_ID,
	PREVIOUS_REQUEST_DATE,
	REPEAT_REQUEST_FLAG,
	REPEAT_REQUEST_WITHIN_90_DAYS_FLAG,
	DAYS_BETWEEN_REQUESTS,
	TOTAL_REQUESTS_FOR_ASSET
) as

WITH REQUEST_HISTORY AS (

    SELECT

        CUSTOMER_ID,
        ASSET_ID,
        SERVICE_REQUEST_ID,
        SERVICE_CREATED_AT,
        SERVICE_TYPE,
        SERVICE_STATUS,
        PRIORITY,
        REGION,
        COUNTRY,

        LAG(SERVICE_CREATED_AT) OVER (
            PARTITION BY CUSTOMER_ID, ASSET_ID
            ORDER BY SERVICE_CREATED_AT
        ) AS PREVIOUS_REQUEST_DATE,

        LAG(SERVICE_REQUEST_ID) OVER (
            PARTITION BY CUSTOMER_ID, ASSET_ID
            ORDER BY SERVICE_CREATED_AT
        ) AS PREVIOUS_SERVICE_REQUEST_ID,

        COUNT(*) OVER (
            PARTITION BY CUSTOMER_ID, ASSET_ID
        ) AS TOTAL_REQUESTS_FOR_ASSET

    FROM STAGING.STG_SERVICE_REQUESTS

)

SELECT

    CUSTOMER_ID,
    ASSET_ID,
    SERVICE_REQUEST_ID,
    SERVICE_CREATED_AT,
    SERVICE_TYPE,
    SERVICE_STATUS,
    PRIORITY,
    REGION,
    COUNTRY,

    PREVIOUS_SERVICE_REQUEST_ID,
    PREVIOUS_REQUEST_DATE,

    CASE
        WHEN PREVIOUS_REQUEST_DATE IS NOT NULL
        THEN TRUE
        ELSE FALSE
    END AS REPEAT_REQUEST_FLAG,

    CASE
        WHEN PREVIOUS_REQUEST_DATE IS NOT NULL
             AND DATEDIFF('DAY', PREVIOUS_REQUEST_DATE, SERVICE_CREATED_AT) <= 90
        THEN TRUE
        ELSE FALSE
    END AS REPEAT_REQUEST_WITHIN_90_DAYS_FLAG,

    DATEDIFF(
        'DAY',
        PREVIOUS_REQUEST_DATE,
        SERVICE_CREATED_AT
    ) AS DAYS_BETWEEN_REQUESTS,

    TOTAL_REQUESTS_FOR_ASSET

FROM REQUEST_HISTORY;
