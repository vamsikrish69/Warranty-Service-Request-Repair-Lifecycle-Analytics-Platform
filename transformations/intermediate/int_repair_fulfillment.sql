create or replace view WARRANTY_SERVICE_ANALYTICS_DB.INTERMEDIATE.INT_REPAIR_FULFILLMENT(
	CONTACT_ID,
	CUSTOMER_ID,
	ASSET_ID,
	CONTACT_CHANNEL,
	CONTACT_TIMESTAMP,
	ISSUE_CATEGORY,
	ISSUE_DESCRIPTION,
	REGION,
	COUNTRY,
	TROUBLESHOOTING_ATTEMPTED_FLAG,
	RESOLVED_DURING_CONTACT_FLAG,
	FOLLOWUP_REQUIRED_FLAG,
	SERVICE_REQUIRED_FLAG,
	SERVICE_REQUEST_ID,
	SERVICE_CREATED_AT,
	SERVICE_TYPE,
	SERVICE_STATUS,
	PRIORITY,
	SLA_TARGET_HOURS,
	ESCALATION_FLAG,
	REPEAT_REQUEST_FLAG,
	CREATED_BY_CHANNEL,
	CONTACT_TO_SERVICE_HOURS,
	SERVICE_CREATED_FLAG,
	FIRST_CONTACT_RESOLVED_FLAG,
	CONTACT_CONVERTED_TO_SERVICE_FLAG,
	WARRANTY_ID,
	WARRANTY_TYPE,
	ENTITLEMENT_LEVEL,
	WARRANTY_STATUS,
	REPAIR_COVERAGE_TYPE,
	ONSITE_ELIGIBLE_FLAG,
	MAILIN_ELIGIBLE_FLAG,
	WARRANTY_START_DATE,
	WARRANTY_END_DATE,
	WARRANTY_FOUND_FLAG,
	ACTIVE_WARRANTY_FLAG,
	EXPIRED_WARRANTY_FLAG,
	ONSITE_REPAIR_ELIGIBLE_FLAG,
	MAILIN_REPAIR_ELIGIBLE_FLAG,
	REPAIR_EVENT_ID,
	REPAIR_TYPE,
	REPAIR_CENTER_ID,
	TECHNICIAN_ID,
	REPAIR_CREATED_AT,
	REPAIR_STARTED_AT,
	REPAIR_COMPLETED_AT,
	PARTS_REQUIRED_FLAG,
	PART_DELAY_FLAG,
	REPAIR_STATUS,
	REPAIR_OUTCOME,
	REPAIR_WAIT_TIME_HOURS,
	REPAIR_TURNAROUND_HOURS,
	REPAIR_EVENT_CREATED_FLAG,
	REPAIR_COMPLETED_FLAG,
	PART_DELAY_IMPACT_FLAG,
	OPEN_REPAIR_FLAG
) as

SELECT
    w.*,

    r.REPAIR_EVENT_ID,
    r.REPAIR_TYPE,
    r.REPAIR_CENTER_ID,
    r.TECHNICIAN_ID,
    r.REPAIR_CREATED_AT,
    r.REPAIR_STARTED_AT,
    r.REPAIR_COMPLETED_AT,
    r.PARTS_REQUIRED_FLAG,
    r.PART_DELAY_FLAG,
    r.REPAIR_STATUS,
    r.REPAIR_OUTCOME,

    DATEDIFF(
        'HOUR',
        r.REPAIR_CREATED_AT,
        r.REPAIR_STARTED_AT
    ) AS REPAIR_WAIT_TIME_HOURS,

    DATEDIFF(
        'HOUR',
        r.REPAIR_STARTED_AT,
        r.REPAIR_COMPLETED_AT
    ) AS REPAIR_TURNAROUND_HOURS,

    CASE
        WHEN r.REPAIR_EVENT_ID IS NOT NULL THEN TRUE
        ELSE FALSE
    END AS REPAIR_EVENT_CREATED_FLAG,

    CASE
        WHEN r.REPAIR_STATUS = 'COMPLETED' THEN TRUE
        ELSE FALSE
    END AS REPAIR_COMPLETED_FLAG,

    CASE
        WHEN r.PART_DELAY_FLAG = TRUE THEN TRUE
        ELSE FALSE
    END AS PART_DELAY_IMPACT_FLAG,

    CASE
        WHEN r.REPAIR_COMPLETED_AT IS NULL
             AND r.REPAIR_EVENT_ID IS NOT NULL
        THEN TRUE
        ELSE FALSE
    END AS OPEN_REPAIR_FLAG

FROM INTERMEDIATE.INT_WARRANTY_VALIDATION w

LEFT JOIN STAGING.STG_REPAIR_EVENTS r
    ON w.SERVICE_REQUEST_ID = r.SERVICE_REQUEST_ID;
