CREATE OR REPLACE VIEW INTERMEDIATE.INT_REPAIR_FULFILLMENT AS

SELECT

    w.*,

    r.REPAIR_EVENT_ID,
    r.REPAIR_TYPE,

    r.REPAIR_CENTER_ID,
    r.TECHNICIAN_ID,

    r.REPAIR_CREATED_AT,
    r.REPAIR_STARTED_AT,
    r.REPAIR_COMPLETED_AT,

    r.PARTS_REQUIRED_FLAG,
    r.PART_DELAY_FLAG,

    r.REPAIR_STATUS,
    r.REPAIR_OUTCOME,

    DATEDIFF(
        'HOUR',
        r.REPAIR_STARTED_AT,
        r.REPAIR_COMPLETED_AT
    ) AS REPAIR_TURNAROUND_HOURS

FROM INTERMEDIATE.INT_WARRANTY_VALIDATION w

LEFT JOIN STAGING.STG_REPAIR_EVENTS r
    ON w.SERVICE_REQUEST_ID = r.SERVICE_REQUEST_ID;




