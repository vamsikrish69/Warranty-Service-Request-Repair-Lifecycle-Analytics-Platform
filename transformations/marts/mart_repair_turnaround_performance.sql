create or replace view WARRANTY_SERVICE_ANALYTICS_DB.MARTS.MART_REPAIR_TURNAROUND_PERFORMANCE(
	REPAIR_TYPE,
	SERVICE_TYPE,
	REPAIR_STATUS,
	REPAIR_OUTCOME,
	TOTAL_SERVICE_REQUESTS,
	TOTAL_REPAIR_EVENTS,
	COMPLETED_REPAIRS,
	OPEN_REPAIRS,
	REPAIRS_REQUIRING_PARTS,
	REPAIRS_WITH_PART_DELAY,
	AVG_REPAIR_WAIT_TIME_HOURS,
	AVG_REPAIR_TURNAROUND_HOURS,
	MEDIAN_REPAIR_TURNAROUND_HOURS,
	REPAIR_COMPLETION_RATE,
	PART_DELAY_RATE
) as

SELECT
    REPAIR_TYPE,
    SERVICE_TYPE,
    REPAIR_STATUS,
    REPAIR_OUTCOME,

    COUNT(DISTINCT SERVICE_REQUEST_ID) AS TOTAL_SERVICE_REQUESTS,

    COUNT(DISTINCT REPAIR_EVENT_ID) AS TOTAL_REPAIR_EVENTS,

    COUNT(
        CASE
            WHEN REPAIR_COMPLETED_FLAG = TRUE THEN REPAIR_EVENT_ID
        END
    ) AS COMPLETED_REPAIRS,

    COUNT(
        CASE
            WHEN OPEN_REPAIR_FLAG = TRUE THEN REPAIR_EVENT_ID
        END
    ) AS OPEN_REPAIRS,

    COUNT(
        CASE
            WHEN PARTS_REQUIRED_FLAG = TRUE THEN REPAIR_EVENT_ID
        END
    ) AS REPAIRS_REQUIRING_PARTS,

    COUNT(
        CASE
            WHEN PART_DELAY_IMPACT_FLAG = TRUE THEN REPAIR_EVENT_ID
        END
    ) AS REPAIRS_WITH_PART_DELAY,

    ROUND(
        AVG(REPAIR_WAIT_TIME_HOURS),
        2
    ) AS AVG_REPAIR_WAIT_TIME_HOURS,

    ROUND(
        AVG(REPAIR_TURNAROUND_HOURS),
        2
    ) AS AVG_REPAIR_TURNAROUND_HOURS,

    ROUND(
        MEDIAN(REPAIR_TURNAROUND_HOURS),
        2
    ) AS MEDIAN_REPAIR_TURNAROUND_HOURS,

    ROUND(
        COUNT(
            CASE
                WHEN REPAIR_COMPLETED_FLAG = TRUE THEN REPAIR_EVENT_ID
            END
        ) * 100.0 / NULLIF(COUNT(DISTINCT REPAIR_EVENT_ID), 0),
        2
    ) AS REPAIR_COMPLETION_RATE,

    ROUND(
        COUNT(
            CASE
                WHEN PART_DELAY_IMPACT_FLAG = TRUE THEN REPAIR_EVENT_ID
            END
        ) * 100.0 / NULLIF(COUNT(DISTINCT REPAIR_EVENT_ID), 0),
        2
    ) AS PART_DELAY_RATE

FROM INTERMEDIATE.INT_REPAIR_FULFILLMENT

WHERE REPAIR_EVENT_ID IS NOT NULL

GROUP BY
    REPAIR_TYPE,
    SERVICE_TYPE,
    REPAIR_STATUS,
    REPAIR_OUTCOME;
