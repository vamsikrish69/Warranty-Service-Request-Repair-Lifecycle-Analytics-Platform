create or replace view WARRANTY_SERVICE_ANALYTICS_DB.MARTS.MART_WARRANTY_UTILIZATION(
	WARRANTY_TYPE,
	ENTITLEMENT_LEVEL,
	WARRANTY_STATUS,
	REPAIR_COVERAGE_TYPE,
	TOTAL_ASSETS,
	TOTAL_CUSTOMERS,
	TOTAL_SUPPORT_CONTACTS,
	TOTAL_SERVICE_REQUESTS,
	ACTIVE_WARRANTY_CONTACTS,
	EXPIRED_WARRANTY_CONTACTS,
	MAIL_IN_SERVICE_REQUESTS,
	ONSITE_SERVICE_REQUESTS,
	ONSITE_ELIGIBLE_RECORDS,
	MAILIN_ELIGIBLE_RECORDS,
	CONTACT_TO_SERVICE_CONVERSION_RATE
) as

SELECT
    WARRANTY_TYPE,
    ENTITLEMENT_LEVEL,
    WARRANTY_STATUS,
    REPAIR_COVERAGE_TYPE,

    COUNT(DISTINCT ASSET_ID) AS TOTAL_ASSETS,

    COUNT(DISTINCT CUSTOMER_ID) AS TOTAL_CUSTOMERS,

    COUNT(DISTINCT CONTACT_ID) AS TOTAL_SUPPORT_CONTACTS,

    COUNT(DISTINCT SERVICE_REQUEST_ID) AS TOTAL_SERVICE_REQUESTS,

    COUNT(
        CASE
            WHEN ACTIVE_WARRANTY_FLAG = TRUE THEN CONTACT_ID
        END
    ) AS ACTIVE_WARRANTY_CONTACTS,

    COUNT(
        CASE
            WHEN EXPIRED_WARRANTY_FLAG = TRUE THEN CONTACT_ID
        END
    ) AS EXPIRED_WARRANTY_CONTACTS,

    COUNT(
        CASE
            WHEN SERVICE_TYPE = 'MAIL_IN_REPAIR' THEN SERVICE_REQUEST_ID
        END
    ) AS MAIL_IN_SERVICE_REQUESTS,

    COUNT(
        CASE
            WHEN SERVICE_TYPE = 'ONSITE_REPAIR' THEN SERVICE_REQUEST_ID
        END
    ) AS ONSITE_SERVICE_REQUESTS,

    COUNT(
        CASE
            WHEN ONSITE_REPAIR_ELIGIBLE_FLAG = TRUE THEN ASSET_ID
        END
    ) AS ONSITE_ELIGIBLE_RECORDS,

    COUNT(
        CASE
            WHEN MAILIN_REPAIR_ELIGIBLE_FLAG = TRUE THEN ASSET_ID
        END
    ) AS MAILIN_ELIGIBLE_RECORDS,

    ROUND(
        COUNT(DISTINCT SERVICE_REQUEST_ID) * 100.0
        / NULLIF(COUNT(DISTINCT CONTACT_ID), 0),
        2
    ) AS CONTACT_TO_SERVICE_CONVERSION_RATE

FROM INTERMEDIATE.INT_WARRANTY_VALIDATION

GROUP BY
    WARRANTY_TYPE,
    ENTITLEMENT_LEVEL,
    WARRANTY_STATUS,
    REPAIR_COVERAGE_TYPE;
