CREATE OR REPLACE VIEW MARTS.MART_WARRANTY_UTILIZATION AS

SELECT

    WARRANTY_TYPE,
    ENTITLEMENT_LEVEL,
    WARRANTY_STATUS,
    REPAIR_COVERAGE_TYPE,

    COUNT(DISTINCT ASSET_ID) AS TOTAL_ASSETS,

    COUNT(DISTINCT CUSTOMER_ID) AS TOTAL_CUSTOMERS,

    COUNT(DISTINCT CONTACT_ID) AS TOTAL_SUPPORT_CONTACTS,

    COUNT(DISTINCT SERVICE_REQUEST_ID) AS TOTAL_SERVICE_REQUESTS,

    COUNT(
        CASE
            WHEN SERVICE_TYPE = 'MAIL_IN_REPAIR'
            THEN SERVICE_REQUEST_ID
        END
    ) AS MAIL_IN_SERVICE_REQUESTS,

    COUNT(
        CASE
            WHEN SERVICE_TYPE = 'ONSITE_REPAIR'
            THEN SERVICE_REQUEST_ID
        END
    ) AS ONSITE_SERVICE_REQUESTS,

    COUNT(
        CASE
            WHEN WARRANTY_STATUS = 'ACTIVE'
            THEN SERVICE_REQUEST_ID
        END
    ) AS ACTIVE_WARRANTY_SERVICE_REQUESTS,

    COUNT(
        CASE
            WHEN WARRANTY_STATUS = 'EXPIRED'
            THEN CONTACT_ID
        END
    ) AS EXPIRED_WARRANTY_CONTACTS,

    ROUND(
        COUNT(DISTINCT SERVICE_REQUEST_ID) * 100.0 / NULLIF(COUNT(DISTINCT CONTACT_ID), 0),
        2
    ) AS WARRANTY_SERVICE_CONVERSION_RATE

FROM INTERMEDIATE.INT_WARRANTY_VALIDATION

GROUP BY
    WARRANTY_TYPE,
    ENTITLEMENT_LEVEL,
    WARRANTY_STATUS,
    REPAIR_COVERAGE_TYPE;
