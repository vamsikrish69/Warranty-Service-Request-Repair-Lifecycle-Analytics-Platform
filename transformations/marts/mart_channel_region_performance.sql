CREATE OR REPLACE VIEW MARTS.MART_CHANNEL_REGION_PERFORMANCE AS

SELECT

    CONTACT_CHANNEL,
    REGION,
    COUNTRY,

    COUNT(DISTINCT CONTACT_ID) AS TOTAL_CONTACTS,

    COUNT(DISTINCT SERVICE_REQUEST_ID) AS TOTAL_SERVICE_REQUESTS,

    COUNT(
        CASE
            WHEN RESOLVED_DURING_CONTACT_FLAG = TRUE
            THEN CONTACT_ID
        END
    ) AS FIRST_CONTACT_RESOLUTIONS,

    COUNT(
        CASE
            WHEN ESCALATION_FLAG = TRUE
            THEN SERVICE_REQUEST_ID
        END
    ) AS ESCALATED_SERVICE_REQUESTS,

    COUNT(
        CASE
            WHEN RESOLUTION_STATUS = 'RESOLVED'
            THEN SERVICE_REQUEST_ID
        END
    ) AS RESOLVED_SERVICE_REQUESTS,

    COUNT(
        CASE
            WHEN REOPEN_FLAG = TRUE
            THEN SERVICE_REQUEST_ID
        END
    ) AS REOPENED_SERVICE_REQUESTS,

    ROUND(
        COUNT(DISTINCT SERVICE_REQUEST_ID) * 100.0 / NULLIF(COUNT(DISTINCT CONTACT_ID), 0),
        2
    ) AS CONTACT_TO_SERVICE_CONVERSION_RATE,

    ROUND(
        COUNT(
            CASE
                WHEN RESOLVED_DURING_CONTACT_FLAG = TRUE
                THEN CONTACT_ID
            END
        ) * 100.0 / NULLIF(COUNT(DISTINCT CONTACT_ID), 0),
        2
    ) AS FIRST_CONTACT_RESOLUTION_RATE,

    ROUND(
        COUNT(
            CASE
                WHEN ESCALATION_FLAG = TRUE
                THEN SERVICE_REQUEST_ID
            END
        ) * 100.0 / NULLIF(COUNT(DISTINCT SERVICE_REQUEST_ID), 0),
        2
    ) AS ESCALATION_RATE,

    ROUND(
        COUNT(
            CASE
                WHEN REOPEN_FLAG = TRUE
                THEN SERVICE_REQUEST_ID
            END
        ) * 100.0 / NULLIF(COUNT(DISTINCT SERVICE_REQUEST_ID), 0),
        2
    ) AS REOPEN_RATE,

    ROUND(
        AVG(TOTAL_LIFECYCLE_HOURS),
        2
    ) AS AVG_LIFECYCLE_HOURS

FROM INTERMEDIATE.INT_CASE_RESOLUTION

GROUP BY
    CONTACT_CHANNEL,
    REGION,
    COUNTRY;





