CREATE OR REPLACE VIEW MARTS.MART_SLA_ADHERENCE AS

SELECT

    SERVICE_REQUEST_ID,
    CUSTOMER_ID,
    ASSET_ID,

    CONTACT_CHANNEL,
    ISSUE_CATEGORY,

    SERVICE_TYPE,
    SERVICE_STATUS,
    PRIORITY,

    SLA_TARGET_HOURS,
    TOTAL_LIFECYCLE_HOURS,

    CASE
        WHEN TOTAL_LIFECYCLE_HOURS IS NULL THEN 'OPEN_OR_PENDING'
        WHEN TOTAL_LIFECYCLE_HOURS <= SLA_TARGET_HOURS THEN 'SLA_MET'
        ELSE 'SLA_BREACHED'
    END AS SLA_STATUS,

    CASE
        WHEN TOTAL_LIFECYCLE_HOURS IS NOT NULL
             AND TOTAL_LIFECYCLE_HOURS <= SLA_TARGET_HOURS
        THEN TRUE
        ELSE FALSE
    END AS SLA_MET_FLAG,

    CASE
        WHEN TOTAL_LIFECYCLE_HOURS IS NOT NULL
             AND TOTAL_LIFECYCLE_HOURS > SLA_TARGET_HOURS
        THEN TRUE
        ELSE FALSE
    END AS SLA_BREACHED_FLAG,

    ESCALATION_FLAG,
    RESOLUTION_STATUS,
    REOPEN_FLAG,

    CONTACT_TIMESTAMP,
    SERVICE_CREATED_AT,
    CASE_CLOSED_AT

FROM INTERMEDIATE.INT_CASE_RESOLUTION

WHERE SERVICE_REQUEST_ID IS NOT NULL;
