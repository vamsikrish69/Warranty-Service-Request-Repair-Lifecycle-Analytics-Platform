create or replace view WARRANTY_SERVICE_ANALYTICS_DB.MARTS.MART_PRODUCT_ISSUE_TRENDS(
	PRODUCT_LINE,
	PRODUCT_MODEL,
	ISSUE_CATEGORY,
	TOTAL_ISSUE_CONTACTS,
	TOTAL_SERVICE_REQUESTS,
	REPEAT_SERVICE_REQUESTS,
	ESCALATED_SERVICE_REQUESTS,
	ISSUE_RANK,
	ISSUE_TO_SERVICE_REQUEST_RATE,
	REPEAT_SERVICE_REQUEST_RATE,
	ESCALATION_RATE
) as

WITH ISSUE_COUNTS AS (

    SELECT
        p.PRODUCT_LINE,
        p.PRODUCT_MODEL,
        c.ISSUE_CATEGORY,

        COUNT(DISTINCT c.CONTACT_ID) AS TOTAL_ISSUE_CONTACTS,

        COUNT(DISTINCT s.SERVICE_REQUEST_ID) AS TOTAL_SERVICE_REQUESTS,

        COUNT(
            CASE
                WHEN s.REPEAT_REQUEST_FLAG = TRUE THEN s.SERVICE_REQUEST_ID
            END
        ) AS REPEAT_SERVICE_REQUESTS,

        COUNT(
            CASE
                WHEN s.ESCALATION_FLAG = TRUE THEN s.SERVICE_REQUEST_ID
            END
        ) AS ESCALATED_SERVICE_REQUESTS

    FROM STAGING.STG_CUSTOMER_CONTACTS c

    LEFT JOIN STAGING.STG_PRODUCT_ASSETS p
        ON c.ASSET_ID = p.ASSET_ID

    LEFT JOIN STAGING.STG_SERVICE_REQUESTS s
        ON c.CONTACT_ID = s.CONTACT_ID

    GROUP BY
        p.PRODUCT_LINE,
        p.PRODUCT_MODEL,
        c.ISSUE_CATEGORY

),

RANKED_ISSUES AS (

    SELECT
        PRODUCT_LINE,
        PRODUCT_MODEL,
        ISSUE_CATEGORY,

        TOTAL_ISSUE_CONTACTS,
        TOTAL_SERVICE_REQUESTS,
        REPEAT_SERVICE_REQUESTS,
        ESCALATED_SERVICE_REQUESTS,

        RANK() OVER (
            PARTITION BY PRODUCT_LINE, PRODUCT_MODEL
            ORDER BY TOTAL_ISSUE_CONTACTS DESC
        ) AS ISSUE_RANK

    FROM ISSUE_COUNTS

)

SELECT
    PRODUCT_LINE,
    PRODUCT_MODEL,
    ISSUE_CATEGORY,

    TOTAL_ISSUE_CONTACTS,
    TOTAL_SERVICE_REQUESTS,
    REPEAT_SERVICE_REQUESTS,
    ESCALATED_SERVICE_REQUESTS,

    ISSUE_RANK,

    ROUND(
        TOTAL_SERVICE_REQUESTS * 100.0
        / NULLIF(TOTAL_ISSUE_CONTACTS, 0),
        2
    ) AS ISSUE_TO_SERVICE_REQUEST_RATE,

    ROUND(
        REPEAT_SERVICE_REQUESTS * 100.0
        / NULLIF(TOTAL_SERVICE_REQUESTS, 0),
        2
    ) AS REPEAT_SERVICE_REQUEST_RATE,

    ROUND(
        ESCALATED_SERVICE_REQUESTS * 100.0
        / NULLIF(TOTAL_SERVICE_REQUESTS, 0),
        2
    ) AS ESCALATION_RATE

FROM RANKED_ISSUES;
