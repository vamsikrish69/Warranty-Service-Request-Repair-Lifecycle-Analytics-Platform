CREATE OR REPLACE VIEW MARTS.MART_SERVICE_REQUEST_LIFECYCLE AS

SELECT

    CONTACT_ID,
    CUSTOMER_ID,
    ASSET_ID,

    CONTACT_CHANNEL,
    CONTACT_TIMESTAMP,

    ISSUE_CATEGORY,
    ISSUE_DESCRIPTION,

    TROUBLESHOOTING_ATTEMPTED_FLAG,
    RESOLVED_DURING_CONTACT_FLAG,

    SERVICE_REQUEST_ID,
    SERVICE_CREATED_AT,
    SERVICE_TYPE,
    SERVICE_STATUS,
    PRIORITY,

    WARRANTY_ID,
    WARRANTY_TYPE,
    ENTITLEMENT_LEVEL,
    WARRANTY_STATUS,
    REPAIR_COVERAGE_TYPE,

    REPAIR_EVENT_ID,
    REPAIR_TYPE,
    REPAIR_STATUS,
    REPAIR_OUTCOME,

    CLOSURE_ID,
    CASE_CLOSED_AT,
    CLOSURE_REASON,
    RESOLUTION_STATUS,
    CUSTOMER_SATISFACTION_SCORE,
    REOPEN_FLAG,

    CONTACT_TO_SERVICE_HOURS,
    REPAIR_TURNAROUND_HOURS,
    TOTAL_LIFECYCLE_HOURS,

    DATEDIFF(
        'DAY',
        CONTACT_TIMESTAMP,
        CURRENT_TIMESTAMP
    ) AS REQUEST_AGE_DAYS,

    CASE
        WHEN SERVICE_REQUEST_ID IS NOT NULL THEN TRUE
        ELSE FALSE
    END AS SERVICE_CREATED_FLAG,

    CASE
        WHEN RESOLUTION_STATUS = 'RESOLVED' THEN TRUE
        ELSE FALSE
    END AS RESOLVED_FLAG,

    CASE
        WHEN REOPEN_FLAG = TRUE THEN TRUE
        ELSE FALSE
    END AS REOPENED_CASE_FLAG

FROM INTERMEDIATE.INT_CASE_RESOLUTION;
``
